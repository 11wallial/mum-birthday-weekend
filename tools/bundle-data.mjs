#!/usr/bin/env node
// Bakes /data into a single JS file so the browser build works from file://
// as well as over http. The JSON stays the source of truth; this is generated.
//   node tools/bundle-data.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const FILES = { customers: 'customers.json', fixtures: 'fixtures.json', economy: 'economy.json', run: 'run.json' };
const data = {};
for (const [key, file] of Object.entries(FILES)) {
  data[key] = JSON.parse(readFileSync(join(ROOT, 'data', file), 'utf8'));
}
writeFileSync(
  join(ROOT, 'game', 'data-bundle.js'),
  `// GENERATED by tools/bundle-data.mjs — edit /data, not this file.\n`
  + `window.FOOTFALL_DATA = ${JSON.stringify(data)};\n`,
);
console.log('game/data-bundle.js written');
